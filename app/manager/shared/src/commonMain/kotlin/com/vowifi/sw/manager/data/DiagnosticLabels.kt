package com.vowifi.sw.manager.data

internal object DiagnosticLabels {
    fun summary(event: DiagnosticEvent): String = buildString {
        append(when (event.component) {
            DiagnosticComponent.APP -> "管理 App"
            DiagnosticComponent.SUBSCRIPTIONS -> "SIM 订阅"
            DiagnosticComponent.CONFIGURATION -> "配置"
            DiagnosticComponent.UNDERLAY -> "底层网络"
            DiagnosticComponent.MODULE -> "模块"
            DiagnosticComponent.ENGINE -> "引擎"
            DiagnosticComponent.DNS -> "DNS"
            DiagnosticComponent.TUNNEL -> "外层连接"
        })
        append(" · ")
        append(when (event.stage) {
            DiagnosticStage.PROCESS -> "进程"
            DiagnosticStage.PERMISSION -> "权限"
            DiagnosticStage.ENUMERATE -> "枚举"
            DiagnosticStage.IDENTITY -> "身份读取"
            DiagnosticStage.NORMALIZE -> "身份规范化"
            DiagnosticStage.LISTENER -> "订阅监听"
            DiagnosticStage.CONFIG_MATCH -> "配置匹配"
            DiagnosticStage.CONFIG_CREATE -> "配置创建"
            DiagnosticStage.CONFIG_REFRESH -> "身份刷新"
            DiagnosticStage.CONFIG_APPLY -> "配置保存"
            DiagnosticStage.STRICT_VERIFY -> "严格核对"
            DiagnosticStage.DISCOVER -> "网络发现"
            DiagnosticStage.PUBLISH -> "快照发布"
            DiagnosticStage.SNAPSHOT -> "快照读取"
            DiagnosticStage.SELECT -> "网络选择"
            DiagnosticStage.SOURCE -> "源地址选择"
            DiagnosticStage.DNS -> "DNS 查询"
            DiagnosticStage.SOCKET -> "套接字建立"
            DiagnosticStage.SOCKET_CONTROL -> "套接字绑定前控制"
            DiagnosticStage.WRITE -> "本地写入"
            DiagnosticStage.RESPONSE -> "收到字节"
            DiagnosticStage.CONNECT -> "连接"
            DiagnosticStage.STOP -> "停止"
        })
        append("：")
        append(when (event.result) {
            DiagnosticResult.OBSERVED -> "已观察"
            DiagnosticResult.STARTED -> "开始"
            DiagnosticResult.SUCCESS -> "成功"
            DiagnosticResult.FAILURE -> "失败"
            DiagnosticResult.CANCELLED -> "已取消"
            DiagnosticResult.UNAVAILABLE -> "不可用"
            DiagnosticResult.STOPPED -> "已停止"
        })
        if (event.reason != DiagnosticReason.NONE) {
            append("，")
            append(when (event.reason) {
                DiagnosticReason.NONE -> ""
                DiagnosticReason.UNKNOWN -> "原因未知"
                DiagnosticReason.UNAVAILABLE -> "数据不可用"
                DiagnosticReason.PERMISSION_DENIED -> "权限不足"
                DiagnosticReason.ROOT_DENIED -> "Root 未授权"
                DiagnosticReason.EMPTY -> "数据为空"
                DiagnosticReason.INVALID_LENGTH -> "身份长度不合法"
                DiagnosticReason.UNSUPPORTED_CHARACTERS -> "身份包含不支持的字符"
                DiagnosticReason.LISTENER_FAILED -> "监听注册失败"
                DiagnosticReason.IO_FAILED -> "本地读写失败"
                DiagnosticReason.LOCK_BUSY -> "已有诊断写入者"
                DiagnosticReason.UNSAFE_PATH -> "诊断路径不安全"
                DiagnosticReason.STORAGE_LIMIT -> "诊断存储超出预算或存在未纳管文件"
                DiagnosticReason.ROTATION_FAILED -> "日志轮转失败"
                DiagnosticReason.USER_STOP -> "用户停止"
                DiagnosticReason.NETWORK_PROPERTIES_CHANGED -> "网络物理属性变化"
                DiagnosticReason.ACCESS_CONTEXT_CHANGED -> "接入上下文变化"
                DiagnosticReason.SNAPSHOT_INVALIDATED -> "网络快照失效"
                DiagnosticReason.SIM_RETIRED -> "SIM 身份退役"
                DiagnosticReason.CANCEL_UNKNOWN -> "取消原因未知"
                DiagnosticReason.CAPABILITIES_MISSING -> "尚未收到网络能力"
                DiagnosticReason.LINK_PROPERTIES_MISSING -> "尚未收到链路属性"
                DiagnosticReason.NETWORK_BLOCKED -> "网络被系统阻止"
                DiagnosticReason.NO_INTERNET -> "缺少互联网能力"
                DiagnosticReason.INVALID_INTERFACE -> "接口名称无效"
                DiagnosticReason.ADDRESS_UNAVAILABLE -> "无可用源地址"
                DiagnosticReason.DNS_UNAVAILABLE -> "无可用 DNS"
                DiagnosticReason.FAMILY_MISMATCH -> "源地址与 DNS 地址族不兼容"
                DiagnosticReason.LIMIT_REACHED -> "超出条目预算"
                DiagnosticReason.INVALID_RESPONSE -> "响应形状无效"
                DiagnosticReason.TIMEOUT -> "操作超时"
                DiagnosticReason.IDENTITY_MISMATCH -> "SIM 与配置身份不一致"
                DiagnosticReason.TARGET_RUNNING -> "目标实例仍在运行"
                DiagnosticReason.TARGET_EXISTS -> "目标配置已存在"
                DiagnosticReason.PROFILE_UNSUPPORTED -> "配置候选不受支持"
                DiagnosticReason.UNCONFIRMED -> "操作结果未确认"
                DiagnosticReason.NOT_ACTIVE -> "目标不在活动订阅中"
                DiagnosticReason.PUBLISH_FAILED -> "快照发布未确认"
                DiagnosticReason.INVALID_SLOT -> "订阅槽位无效"
                DiagnosticReason.SNAPSHOT_MISSING -> "网络快照尚不存在"
                DiagnosticReason.VERSION_UNSUPPORTED -> "快照版本不受支持"
                DiagnosticReason.BOOT_MISMATCH -> "快照不属于本次系统启动"
                DiagnosticReason.SNAPSHOT_STALE -> "网络快照已过期"
                DiagnosticReason.SNAPSHOT_FUTURE -> "网络快照时间超前"
                DiagnosticReason.NO_CANDIDATE -> "没有匹配的网络候选"
                DiagnosticReason.SELECTOR_INVALID -> "网络选择器无效"
                DiagnosticReason.NETWORK_UNREACHABLE -> "目标网络不可达"
                DiagnosticReason.CONNECTION_REFUSED -> "连接被拒绝"
                DiagnosticReason.BIND_FAILED -> "套接字绑定失败"
                DiagnosticReason.CAPACITY_EXHAUSTED -> "受管日志组额度耗尽"
            })
        }
    }
}
