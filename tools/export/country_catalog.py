"""Parse the pinned public AOSP MCC table into MCC→ISO2 data only."""

# ruff: noqa: D107, EM101

from __future__ import annotations

import hashlib
import os
import re
import tempfile
from dataclasses import dataclass
from pathlib import Path
from typing import Final, Literal

PINNED_SHA256: Final = "68a2ed822151f0cdacc023fb924c1dff9bc7e913bcad5220dd1f42503e715840"
PINNED_SIZE: Final = 29630
PINNED_COMMIT: Final = "307806916047d68377ff74674f95ca499243e068"
PINNED_URI: Final = (
    "https://android.googlesource.com/platform/frameworks/opt/telephony/+/"
    f"{PINNED_COMMIT}/src/java/com/android/internal/telephony/MccTable.java"
)
EXPECTED_ENTRIES: Final = 241
EXPECTED_ISO_CODES: Final = 227
FIRST_MCC: Final = "202"
LAST_MCC: Final = "750"
ENTRY_RE: Final = re.compile(
    r'^        sTable\.add\(new MccEntry\(([0-9]{3}), "([^"]*)", [23]\)\);(?: //.*)?$'
)
MCC_RE: Final = re.compile(r"^[0-9]{3}$")
ISO2_RE: Final = re.compile(r"^[a-z]{2}$")
ADD_MARK: Final = "sTable.add(new MccEntry("


class CatalogError(ValueError):
    """Stable generator error code without input values."""

    code: str

    def __init__(self, code: str) -> None:
        self.code = code
        super().__init__(code)


@dataclass(frozen=True, slots=True)
class CountryEntry:
    """One public MCC to lowercase ISO2 pair."""

    mcc: str
    iso2: str


def require_pinned_source(source: bytes) -> None:
    """Reject any bytes that are not the reviewed public pin."""
    digest = hashlib.sha256(source).hexdigest()
    if len(source) != PINNED_SIZE or digest != PINNED_SHA256:
        raise CatalogError("source_digest_mismatch")


def parse_mcc_table(source: bytes) -> tuple[CountryEntry, ...]:
    """Parse only anchored MccEntry rows; fail closed on unexpected format."""
    try:
        text = source.decode("utf-8")
    except UnicodeDecodeError as error:
        raise CatalogError("unexpected_record") from error
    entries: list[CountryEntry] = []
    seen: dict[str, str] = {}
    found = False
    for raw_line in text.split("\n"):
        line = raw_line.removesuffix("\r")
        if ADD_MARK not in line:
            continue
        found = True
        match = ENTRY_RE.fullmatch(line)
        if match is None:
            raise CatalogError("unexpected_record")
        mcc, iso2 = match.group(1), match.group(2)
        if not ISO2_RE.fullmatch(iso2):
            raise CatalogError("invalid_iso")
        if mcc in seen:
            code = "iso_conflict" if seen[mcc] != iso2 else "duplicate_mcc"
            raise CatalogError(code)
        seen[mcc] = iso2
        entries.append(CountryEntry(mcc=mcc, iso2=iso2))
    if not found or not entries:
        raise CatalogError("empty_table")
    return tuple(entries)


def require_public_catalog(entries: tuple[CountryEntry, ...]) -> None:
    """Lock the independently counted public-country contract."""
    mccs = [entry.mcc for entry in entries]
    if (
        len(entries) != EXPECTED_ENTRIES
        or len(set(mccs)) != EXPECTED_ENTRIES
        or mccs != sorted(mccs)
        or mccs[0] != FIRST_MCC
        or mccs[-1] != LAST_MCC
        or len({entry.iso2 for entry in entries}) != EXPECTED_ISO_CODES
    ):
        raise CatalogError("invalid_count")


def iso2_for_mcc(entries: tuple[CountryEntry, ...], mcc: str | None) -> str:
    """Return lowercase ISO2 or empty; never guess a country or operator."""
    if mcc is None or MCC_RE.fullmatch(mcc) is None:
        return ""
    mapping = {entry.mcc: entry.iso2 for entry in entries}
    return mapping.get(mcc, "")


def render_kotlin(entries: tuple[CountryEntry, ...], source_sha256: str) -> bytes:
    """Emit generated Kotlin data with Apache-2.0 and public pin headers."""
    rows = ",\n".join(
        f'        CountryCatalogEntry(mcc = "{entry.mcc}", iso2 = "{entry.iso2}")'
        for entry in entries
    )
    text = f"""\
// Code generated by tools/export/build_country_catalog.py; DO NOT EDIT.
// allow: SIZE_OK — generated public MCC to ISO2 table from pinned AOSP MccTable.java
// Copyright (C) 2006 The Android Open Source Project
// Derived MCC to ISO2 data only; AOSP Java helpers are not copied.
// License: Apache-2.0
// Source: {PINNED_URI}
// Pin: {PINNED_COMMIT}
// Raw-SHA256: {source_sha256}

package com.vowifi.sw.manager.model

internal data class CountryCatalogEntry(
    val mcc: String,
    val iso2: String,
)

internal object CountryCatalogGenerated {{
    const val SOURCE_SHA256 = "{source_sha256}"

    val countries: List<CountryCatalogEntry> = listOf(
{rows},
    )

    private val iso2ByMcc: Map<String, String> = countries.associate {{ it.mcc to it.iso2 }}

    fun countryForMcc(mcc: String?): String {{
        if (mcc == null || mcc.length != 3) return ""
        for (ch in mcc) {{
            if (ch !in '0'..'9') return ""
        }}
        return iso2ByMcc[mcc].orEmpty()
    }}
}}
"""
    return text.encode("utf-8")


def scoped_path(root: Path, raw: str) -> Path:
    """Resolve a path and reject writes or reads outside repo-root."""
    root_resolved = root.resolve()
    candidate = Path(raw)
    path = candidate if candidate.is_absolute() else root_resolved / candidate
    resolved = path.resolve()
    try:
        _ = resolved.relative_to(root_resolved)
    except ValueError as error:
        raise CatalogError("path_out_of_scope") from error
    return resolved


def write_bytes_atomic(path: Path, data: bytes) -> None:
    """Replace the caller-selected output via an exclusive sibling temp file."""
    path.parent.mkdir(parents=True, exist_ok=True)
    fd, tmp_name = tempfile.mkstemp(
        prefix=f".{path.name}.", suffix=".tmp", dir=path.parent,
    )
    tmp = Path(tmp_name)
    transferred = False
    try:
        with os.fdopen(fd, "wb") as handle:
            transferred = True
            _ = handle.write(data)
        _ = tmp.replace(path)
    finally:
        if not transferred:
            os.close(fd)
        tmp.unlink(missing_ok=True)


def build_catalog(source: bytes) -> bytes:
    """Pin, parse, and render the public-country Kotlin table."""
    require_pinned_source(source)
    entries = parse_mcc_table(source)
    require_public_catalog(entries)
    return render_kotlin(entries, PINNED_SHA256)


def generate_catalog(source_path: Path, output_path: Path) -> tuple[int, int]:
    """Write generated Kotlin from the pinned source; return catalog counts."""
    if source_path == output_path:
        raise CatalogError("path_out_of_scope")
    rendered = build_catalog(source_path.read_bytes())
    write_bytes_atomic(output_path, rendered)
    return EXPECTED_ENTRIES, EXPECTED_ISO_CODES


def check_catalog(source_path: Path, output_path: Path) -> tuple[int, int]:
    """Require the output bytes to match a fresh deterministic render."""
    rendered = build_catalog(source_path.read_bytes())
    existing = output_path.read_bytes()
    if existing != rendered:
        raise CatalogError("output_mismatch")
    return EXPECTED_ENTRIES, EXPECTED_ISO_CODES


Command = Literal["generate", "check"]
